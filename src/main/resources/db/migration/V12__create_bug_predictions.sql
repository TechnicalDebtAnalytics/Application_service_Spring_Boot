CREATE TABLE bug_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    -- Prediction applies to one analyzed class metric vector.
    class_id BIGINT NOT NULL,

    -- Normalized ML probability: 0.0 is lowest and 1.0 is highest.
    probability_score DOUBLE PRECISION NOT NULL,

    CONSTRAINT pk_bug_predictions
        PRIMARY KEY (prediction_id),

    -- The current model stores one authoritative prediction per class metric.
    CONSTRAINT uk_bug_predictions_class_id
        UNIQUE (class_id),

    -- Rejects invalid probability values outside the normalized 0.0–1.0 range.
    CONSTRAINT ck_bug_predictions_probability_score
        CHECK (
            probability_score >= 0.0
            AND probability_score <= 1.0
        ),

    -- A generated prediction has no meaning after its class metric is removed.
    CONSTRAINT fk_bug_predictions_class_metrics
        FOREIGN KEY (class_id)
        REFERENCES class_metrics(class_id)
        ON DELETE CASCADE
);

-- No separate class_id index is needed because the UNIQUE constraint creates
-- an index that supports relationship lookups and foreign-key operations.
